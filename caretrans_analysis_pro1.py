import pandas as pd
df = pd.read_csv("/content/HHS_Unaccompanied_Alien_Children_Program.csv")
df.head()

print("Columns are",df.columns)
print("Shape is", df.shape)
print("Info is", df.info())
print("Description is", df.describe())
print("Null values are\n", df.isnull().sum())

df = df.dropna(how='all')
print(df.shape)

df['Date'] = pd.to_datetime(df['Date'])

df.head(10)

df['Children in HHS Care'] = (
    df['Children in HHS Care']
    .astype(str)
    .str.replace(',', '')
    .astype(float)
)

df['Year'] = df['Date'].dt.year
df['Month'] = df['Date'].dt.month
df['Month_Name'] = df['Date'].dt.month_name()
df['Day_Name'] = df['Date'].dt.day_name()
df['Weekday'] = df['Date'].dt.dayofweek

df['Transfer Efficiency'] = (
    (df['Children transferred out of CBP custody']
    / df['Children in CBP custody']).round(3)
)

df['Transfer Efficiency %'] = (df['Transfer Efficiency'] * 100).round(3)

df['Discharge Effectiveness'] = (
    (df['Children discharged from HHS Care']
    / df['Children in HHS Care']).round(3)
)

df['Discharge Effectiveness %'] = (
    (df['Discharge Effectiveness'] * 100).round(3)
)

df['HHS Net Flow'] = (
    df['Children transferred out of CBP custody']
    -
    df['Children discharged from HHS Care']
)

df = df.sort_values('Date')
df['Cumulative Net Flow'] = df['HHS Net Flow'].cumsum()

